"""Memory footprint: count entries per memory type, tests and verifiers; write memory/footprint.md;
show the delta against the last commit; commit and push with the delta in the message.

Usage:
  python scripts/footprint.py --write                     regenerate memory/footprint.md
  python scripts/footprint.py --delta                     print the delta against HEAD's footprint
  python scripts/footprint.py --commit --title "<request>" write, append the run-log line, commit, push
  python scripts/footprint.py --commit --no-push          same without the push

Standard library only. The footprint file carries no timestamps so that the integrity test can compare it
byte for byte with a fresh render.
"""

from __future__ import annotations

import argparse
import datetime as dt
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FOOTPRINT = ROOT / "memory" / "footprint.md"
RUN_LOG = ROOT / "memory" / "run-log.md"
ENTRY_RE = re.compile(r"^### ([A-Z]{1,2})-(\d{3,}): ")
STATUS_RE = re.compile(r"^-- .*\bstatus: (active|superseded|retired)\b")
STATUSES = ("active", "superseded", "retired")

AREAS = [
    ("facts", "facts/*.md"),
    ("rules", "memory/rules.md"),
    ("hints", "memory/hints.md"),
    ("guarantees", "memory/guarantees.md"),
    ("failures", "memory/failures.md"),
    ("verification", "memory/verification.md"),
    ("decisions", "memory/decisions.md"),
    ("open-questions", "memory/open-questions.md"),
    ("workflows", "memory/workflows.md"),
    ("scope", "memory/scope.md"),
    ("glossary", "memory/glossary.md"),
    ("pointers", "memory/pointers.md"),
]

HEADER = """---
title: Memory footprint
description: Counts of entries per memory type, plus tests, verifiers and feedback, regenerated by scripts/footprint.py at the end of every request. Load at the end of a request when reporting how memory changed.
write: scripts/footprint.py only. Never edit by hand.
---

# Memory footprint

| area | active | superseded | retired |
|---|---|---|---|
"""


def _entries_by_status(path: Path) -> dict[str, int]:
    """Count the entries in one file by the status on their metadata line."""
    counts = {status: 0 for status in STATUSES}
    current: str | None = None
    in_fence = False
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.lstrip().startswith("```"):
            in_fence = not in_fence
            continue
        if in_fence:
            continue
        if ENTRY_RE.match(line):
            current = "active"  # an entry without a metadata line counts as active, and the integrity test flags it
            counts[current] += 1
            continue
        match = STATUS_RE.match(line)
        if match and current is not None:
            counts[current] -= 1
            current = match.group(1)
            counts[current] += 1
    return counts


def scan() -> dict:
    """Collect every count the footprint reports."""
    data: dict = {"areas": {}, "feedback": {"logged": 0, "pending": 0}, "tests": {"files": 0, "functions": 0}, "verifiers": 0}
    for area, pattern in AREAS:
        totals = {status: 0 for status in STATUSES}
        for path in sorted(ROOT.glob(pattern)):
            if path.name == "README.md":
                continue
            for status, n in _entries_by_status(path).items():
                totals[status] += n
        data["areas"][area] = totals
    log = ROOT / "memory" / "feedback-log.md"
    if log.exists():
        src = log.read_text(encoding="utf-8")
        data["feedback"]["logged"] = sum(1 for line in src.splitlines() if ENTRY_RE.match(line))
        data["feedback"]["pending"] = sum(1 for line in src.splitlines() if line.startswith("disposition: pending"))
    for path in sorted((ROOT / "tests").glob("test_*.py")):
        data["tests"]["files"] += 1
        data["tests"]["functions"] += sum(1 for line in path.read_text(encoding="utf-8").splitlines() if line.startswith("def test_"))
    skip = {"README.md", "INDEX.md", "_template.md"}
    data["verifiers"] = sum(1 for path in (ROOT / "verifiers").glob("*.md") if path.name not in skip)
    return data


def render(data: dict) -> str:
    """The footprint markdown for a scan result."""
    lines = [HEADER]
    for area, _ in AREAS:
        counts = data["areas"][area]
        lines.append(f"| {area} | {counts['active']} | {counts['superseded']} | {counts['retired']} |\n")
    total_active = sum(c["active"] for c in data["areas"].values())
    lines.append("\n")
    lines.append(f"Feedback: {data['feedback']['logged']} logged, {data['feedback']['pending']} pending\n")
    lines.append(f"Tests: {data['tests']['files']} files, {data['tests']['functions']} functions\n")
    lines.append(f"Verifiers: {data['verifiers']}\n")
    lines.append(f"Total active entries: {total_active}\n")
    return "".join(lines)


def parse(markdown: str) -> dict:
    """Read counts back out of a footprint file; missing parts count as zero."""
    data: dict = {"areas": {area: {s: 0 for s in STATUSES} for area, _ in AREAS}, "feedback": {"logged": 0, "pending": 0}, "tests": {"files": 0, "functions": 0}, "verifiers": 0}
    for match in re.finditer(r"^\| ([a-z-]+) \| (\d+) \| (\d+) \| (\d+) \|$", markdown, re.M):
        area = match.group(1)
        if area in data["areas"]:
            data["areas"][area] = {"active": int(match.group(2)), "superseded": int(match.group(3)), "retired": int(match.group(4))}
    feedback = re.search(r"^Feedback: (\d+) logged, (\d+) pending$", markdown, re.M)
    if feedback:
        data["feedback"] = {"logged": int(feedback.group(1)), "pending": int(feedback.group(2))}
    tests = re.search(r"^Tests: (\d+) files, (\d+) functions$", markdown, re.M)
    if tests:
        data["tests"] = {"files": int(tests.group(1)), "functions": int(tests.group(2))}
    verifiers = re.search(r"^Verifiers: (\d+)$", markdown, re.M)
    if verifiers:
        data["verifiers"] = int(verifiers.group(1))
    return data


def delta(old: dict, new: dict) -> str:
    """A short human sentence describing what changed between two scans."""
    parts: list[str] = []
    for area, _ in AREAS:
        before, after = old["areas"][area], new["areas"][area]
        diff_active = after["active"] - before["active"]
        if diff_active:
            parts.append(f"{diff_active:+d} {area}")
        for status in ("superseded", "retired"):
            diff = after[status] - before[status]
            if diff > 0:
                parts.append(f"{diff} {area} {status}")
    diff_tests = new["tests"]["functions"] - old["tests"]["functions"]
    if diff_tests:
        parts.append(f"{diff_tests:+d} tests")
    diff_verifiers = new["verifiers"] - old["verifiers"]
    if diff_verifiers:
        parts.append(f"{diff_verifiers:+d} verifiers")
    diff_feedback = new["feedback"]["logged"] - old["feedback"]["logged"]
    if diff_feedback:
        parts.append(f"{diff_feedback:+d} feedback")
    if new["feedback"]["pending"]:
        parts.append(f"{new['feedback']['pending']} feedback pending")
    return ", ".join(parts) if parts else "no change"


def git(*args: str, check: bool = True) -> subprocess.CompletedProcess:
    return subprocess.run(["git", *args], cwd=ROOT, text=True, capture_output=True, check=check)


def head_footprint() -> dict:
    """The footprint as of the last commit, or all zeros when there is no commit or no file yet."""
    result = git("show", "HEAD:memory/footprint.md", check=False)
    return parse(result.stdout if result.returncode == 0 else "")


def write() -> dict:
    data = scan()
    FOOTPRINT.write_text(render(data), encoding="utf-8", newline="\n")
    return data


def append_run_log(title: str, change: str) -> None:
    line = f"- {dt.date.today().isoformat()} | {title} | {change}\n"
    src = RUN_LOG.read_text(encoding="utf-8")
    if not src.endswith("\n"):
        src += "\n"
    RUN_LOG.write_text(src + line, encoding="utf-8", newline="\n")


def commit(title: str, push: bool) -> int:
    old = head_footprint()
    new = write()
    change = delta(old, new)
    append_run_log(title, change)
    git("add", "-A")
    if git("diff", "--cached", "--quiet", check=False).returncode == 0:
        print("nothing to commit")
        return 0
    git("commit", "-m", f"memory: {change}", "-m", title)
    print(f"committed: memory: {change}")
    if push:
        if git("remote", "get-url", "origin", check=False).returncode != 0:
            print("no origin remote; skipped push")
            return 0
        pushed = git("push", "-u", "origin", "HEAD", check=False)
        if pushed.returncode != 0:
            print(pushed.stderr.strip() or "push failed")
            return pushed.returncode
        print("pushed")
    return 0


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--write", action="store_true", help="regenerate memory/footprint.md")
    parser.add_argument("--delta", action="store_true", help="print the delta against HEAD")
    parser.add_argument("--commit", action="store_true", help="write, append the run-log line, commit, push")
    parser.add_argument("--title", default="request", help="the request in a few words, for the run log and the commit")
    parser.add_argument("--no-push", action="store_true", help="commit without pushing")
    args = parser.parse_args(argv)
    if args.commit:
        return commit(args.title, push=not args.no_push)
    if args.delta:
        print(delta(head_footprint(), scan()))
        return 0
    write()
    print(f"wrote {FOOTPRINT.relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
